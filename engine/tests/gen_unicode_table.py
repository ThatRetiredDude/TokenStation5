#!/usr/bin/env python3
"""Writes src/unicode_table.h: the code point ranges of Unicode's letters (L),
marks (M) and numbers (N), for the tokenizer's pre-split (\\p{L}, \\p{M} and
\\p{N} in the models' regexes). From Python's own Unicode database.

    python3 engine/tests/gen_unicode_table.py > engine/src/unicode_table.h
"""
import unicodedata

KIND = {"L": 1, "M": 2, "N": 3}


def kind(c):
    if 0xD800 <= c < 0xE000:
        return 0
    return KIND.get(unicodedata.category(chr(c))[0], 0)


ranges, prev, start = [], 0, 0
for c in range(0x110000):
    k = kind(c)
    if k != prev:
        if prev:
            ranges.append((start, c - 1, prev))
        start, prev = c, k
if prev:
    ranges.append((start, 0x10FFFF, prev))

print("// Generated by engine/tests/gen_unicode_table.py from Unicode %s: do not edit." % unicodedata.unidata_version)
print("// Each range's code points are letters (1), marks (2) or numbers (3); the")
print("// rest are none of these. Sorted, so a binary search finds a code point.")
print("#pragma once")
print("#include <cstdint>")
print("namespace ts5 {")
print("struct UnicodeRange { uint32_t lo, hi; uint8_t kind; };")
print("static const UnicodeRange kUnicodeRanges[] = {")
line = ""
for lo, hi, k in ranges:
    item = "{0x%X,0x%X,%d}," % (lo, hi, k)
    if len(line) + len(item) > 116:
        print("    " + line.rstrip())
        line = ""
    line += item
if line:
    print("    " + line.rstrip())
print("};")
print("}  // namespace ts5")
